import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import { getTableConfig } from 'drizzle-orm/sqlite-core';
import { getTableName } from 'drizzle-orm';

// Staging schema only. Applying this does not switch any live application flow.
// Import must additionally preserve source_rowid and reset identity sequences.
const q=s=>'"'+String(s).replaceAll('"','""')+'"';
const literal=v=>typeof v==='boolean'?(v?'1':'0'):typeof v==='number'?String(v):typeof v==='string'?"'"+v.replaceAll("'","''")+"'":(()=>{throw Error('Unsupported schema default');})();
const temporary=path.resolve('.sites-runtime/neon-schema-source.mjs');
await mkdir(path.dirname(temporary),{recursive:true});
await writeFile(temporary,ts.transpileModule(await readFile('db/schema.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
try{
  const schema=await import(pathToFileURL(temporary).href);
  const tables=Object.values(schema).map(table=>getTableConfig(table));
  const ddl=['-- Staging schema for the quotation app. No production cutover.','-- source_rowid retains SQLite pagination order; do not regenerate on import.'];
  const constraints=[],indexes=[],contract={};
  for(const t of tables){
    const columns=t.columns.map(c=>{
      const type=c.getSQLType();
      if(!['text','integer','real','blob'].includes(type))throw Error('Unsupported column type: '+type);
      const pg={text:'TEXT',integer:'BIGINT',real:'DOUBLE PRECISION',blob:'BYTEA'}[type];
      return `${q(c.name)} ${pg}${c.notNull?' NOT NULL':''}${c.default!==undefined?' DEFAULT '+literal(c.default):''}`;
    });
    const primary=[...t.columns.filter(c=>c.primary).map(c=>c.name),...t.primaryKeys.flatMap(p=>p.columns.map(c=>c.name))];
    contract[t.name]={primary,columns:t.columns.map(c=>({name:c.name,type:c.getSQLType()}))};
    columns.push('"source_rowid" BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE');
    if(primary.length)columns.push('PRIMARY KEY ('+primary.map(q).join(',')+')');
    ddl.push(`CREATE TABLE IF NOT EXISTS ${q(t.name)} (\n  ${columns.join(',\n  ')}\n);`);
    for(const f of t.foreignKeys){
      const r=f.reference();
      constraints.push(`ALTER TABLE ${q(t.name)} ADD CONSTRAINT ${q(f.getName())} FOREIGN KEY (${r.columns.map(c=>q(c.name)).join(',')}) REFERENCES ${q(getTableName(r.foreignTable))} (${r.foreignColumns.map(c=>q(c.name)).join(',')}) DEFERRABLE INITIALLY DEFERRED;`);
    }
    for(const i of t.indexes){
      const c=i.config;
      if(c.columns.some(column=>!column.name))throw Error('Expression index needs explicit PostgreSQL translation');
      indexes.push(`CREATE ${c.unique?'UNIQUE ':''}INDEX IF NOT EXISTS ${q(c.name)} ON ${q(t.name)} (${c.columns.map(column=>q(column.name)).join(',')});`);
    }
  }
  // Runtime-created tables are part of the actual source and not in db/schema.ts.
  ddl.push(`CREATE TABLE IF NOT EXISTS printing_workshops (id TEXT PRIMARY KEY,name TEXT NOT NULL,name_key TEXT NOT NULL UNIQUE,tax_code TEXT NOT NULL DEFAULT '',address TEXT NOT NULL DEFAULT '',phone TEXT NOT NULL DEFAULT '',email TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL,created_by TEXT NOT NULL,source_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);`);
  ddl.push(`CREATE TABLE IF NOT EXISTS sapo_runtime_sessions (id TEXT PRIMARY KEY,encrypted_cookie TEXT NOT NULL,updated_at TEXT NOT NULL,updated_by TEXT NOT NULL,source_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);`);
  ddl.push(`CREATE TABLE IF NOT EXISTS vigifts_product_image_map (product_id TEXT PRIMARY KEY,sku TEXT NOT NULL,product_name TEXT NOT NULL,image_file_name TEXT NOT NULL,image_source_path TEXT NOT NULL,image_url TEXT,sync_status TEXT NOT NULL,imported_at TEXT NOT NULL,source_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);`);
  indexes.push('CREATE INDEX IF NOT EXISTS idx_vigifts_product_image_map_sku ON vigifts_product_image_map(sku);');
  indexes.push('CREATE INDEX IF NOT EXISTS idx_quotations_quote_number_lower ON staff_quotations(lower(quote_no));');
  contract.printing_workshops={primary:['id'],columns:['id','name','name_key','tax_code','address','phone','email','created_at','created_by'].map(name=>({name,type:'text'}))};
  contract.sapo_runtime_sessions={primary:['id'],columns:['id','encrypted_cookie','updated_at','updated_by'].map(name=>({name,type:'text'}))};
  contract.vigifts_product_image_map={primary:['product_id'],columns:['product_id','sku','product_name','image_file_name','image_source_path','image_url','sync_status','imported_at'].map(name=>({name,type:'text'}))};
  await mkdir('neon/migrations',{recursive:true});
  const filename='neon/migrations/0002_bao_gia_source_schema.sql';
  await writeFile(filename,[...ddl,...constraints,...indexes].join('\n\n')+'\n');
  await writeFile('lib/neon-table-contract.mjs','// Generated from the checked source schema.\nexport const neonTableContract = '+JSON.stringify(contract,null,2)+';\n');
  console.log(JSON.stringify({filename,tableCount:tables.length+3,stagingOnly:true}));
}finally{await rm(temporary,{force:true});}
